export function getPackage(slug: string) {
  return packages.find((p) => p.slug === slug);
}

export function getPackagesByDestination(destinationSlug: string) {
  return packages.filter((p) => p.destination === destinationSlug);
}

export function getPackagesByCategory(category: string) {
  return packages.filter((p) => p.categories.includes(category as TourPackage["categories"][number]));
}

